def save_datasets():
    import os
    os.makedirs(".", exist_ok=True)
    
    products_out = []
    for p in PRODUCTS:
        pid, name, cat, active, warn, ind = p
        products_out.append({
            "product_id": pid,
            "name": name,
            "category": cat,
            "active_ingredient": active,
            "warnings_keywords": warn,
            "indications": ind,
            "SIMULATION_FLAG": "SYNTHETIC_DATA"
        })
    
    queries_out = []
    for q in QUERIES:
        qid, text, rel, major_safety = q
        queries_out.append({
            "query_id": qid,
            "query_text": text,
            "relevant_product_ids": rel,
            "major_safety_product_ids": major_safety,
            "SIMULATION_FLAG": "SYNTHETIC_DATA"
        })
    
    safety_out = []
    for s in SAFETY_PAIRS:
        pid2, prod, cond, is_major, expected, severity = s
        safety_out.append({
            "pair_id": pid2,
            "product_id": prod,
            "patient_condition": cond,
            "is_major_contraindication": is_major,
            "expected_detection": expected,
            "severity_label": severity,
            "SIMULATION_FLAG": "SYNTHETIC_DATA"
        })
    
    with open("products_catalog.json","w") as f:
        json.dump(products_out, f, indent=2)
    with open("queries_relevance.json","w") as f:
        json.dump(queries_out, f, indent=2)
    with open("safety_pairs.json","w") as f:
        json.dump(safety_out, f, indent=2)
    
    print(f"Products: {len(products_out)}")
    print(f"Queries:  {len(queries_out)}")
    print(f"Safety pairs: {len(safety_out)}")
    print("SIMULATION_FLAG: SYNTHETIC_DATA in all records")

if __name__ == "__main__":
    save_datasets()
